"""Generate procedural grasp-and-lift reference clips (G1 + right Inspire hand).

Each candidate clip is generated by whole-body IK (``supermimic.grasp.clip_gen``),
then its grasp is simulated with a floating hand (``supermimic.grasp.hand_sim``).
Clips whose grasp fails to lift the object are rejected; kept clips take the
simulated object trajectory and contact labels as their object reference.

Writes ``clip_XXXX.npz`` files (mjlab motion keys plus object, contact and scene
keys) and a ``manifest.json``.

  uv run src/supermimic/scripts/gen_grasp_clips.py --out-dir data/grasp_clips
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import tyro

from supermimic.grasp import clip_gen, hand_sim


@dataclass
class GenConfig:
  out_dir: Path = Path("data/grasp_clips")
  num_clips: int = 300
  seed: int = 0
  min_lift: float = 0.08
  """Minimum simulated object rise (m) for a clip to be kept."""
  max_tilt_deg: float = 30.0
  """Maximum simulated object tilt at the end for a clip to be kept."""
  max_attempts_factor: int = 3
  vary_object: bool = False
  """Vary cylinder size and mass; v1 trains on one fixed object."""


def main(cfg: GenConfig) -> None:
  cfg.out_dir.mkdir(parents=True, exist_ok=True)
  rng = np.random.default_rng(cfg.seed)
  ik = clip_gen.WholeBodyIK()
  manifest, attempts = [], 0
  while len(manifest) < cfg.num_clips:
    attempts += 1
    if attempts > cfg.max_attempts_factor * cfg.num_clips:
      raise RuntimeError(f"only {len(manifest)} feasible clips in {attempts} tries")
    params = clip_gen.sample_params(rng, fixed_object=not cfg.vary_object)
    clip = clip_gen.generate_clip(ik, params)
    sim = hand_sim.simulate(ik.model, clip, clip_gen.FPS)
    if sim.lift < cfg.min_lift or sim.tilt_deg > cfg.max_tilt_deg:
      continue
    clip = clip_gen.apply_hand_sim(clip, sim)
    name = f"clip_{len(manifest):04d}.npz"
    np.savez(cfg.out_dir / name, **clip)
    manifest.append(
      {
        "file": name,
        "frames": len(clip["joint_pos"]),
        **asdict(params),
        "sim_lift": round(sim.lift, 4),
        "sim_tilt_deg": round(sim.tilt_deg, 2),
      }
    )
    if len(manifest) % 25 == 0:
      print(f"[INFO] {len(manifest)}/{cfg.num_clips} clips ({attempts} tried)")
  (cfg.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1))
  print(
    f"[INFO] wrote {len(manifest)} clips to {cfg.out_dir}; "
    f"acceptance {len(manifest) / attempts:.0%}"
  )


if __name__ == "__main__":
  main(tyro.cli(GenConfig))
